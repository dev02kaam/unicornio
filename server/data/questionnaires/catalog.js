function numberedQuestions(items) {
  return items.map((text, index) => ({
    number: index + 1,
    type: 'LIKERT_SINGLE',
    text,
    required: true,
  }));
}

function version({
  id,
  familyKey,
  title,
  shortTitle,
  ageMin,
  ageMax,
  instructions,
  questions,
  scoringRules,
}) {
  return {
    id,
    familyKey,
    version: '1.0',
    title,
    shortTitle,
    ageMin,
    ageMax,
    instructions,
    responseScale: RESPONSE_SCALE,
    questions: numberedQuestions(questions),
    scoringRules,
    sourceDocument: SOURCE_DOCUMENT,
    status: 'EXPERIMENTAL',
  };
}

function totalRules({ bands, totalAlertThreshold = null, sentinelRules = [], ...extra }) {
  return {
    minimum: 0,
    maximum: 60,
    bands,
    totalAlertThreshold,
    sentinelRules,
    pendingClinicalRules: [
      'Instrumento experimental pendiente de validación psicométrica y clínica.',
    ],
    ...extra,
  };
}

